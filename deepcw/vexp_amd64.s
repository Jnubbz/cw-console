// func expSubSumAVX(dst, src *float32, n int, sub float32) float32
// dst[i] = exp(src[i]-sub) for i < n (n a multiple of 8); returns the sum.
TEXT ·expSubSumAVX(SB), NOSPLIT, $0-36
	MOVQ         dst+0(FP), DI
	MOVQ         src+8(FP), SI
	MOVQ         n+16(FP), CX
	VBROADCASTSS sub+24(FP), Y15
	VXORPS       Y14, Y14, Y14
	SHRQ         $3, CX
	JZ           esdone
esloop:
	VMOVUPS (SI), Y0
	VSUBPS  Y15, Y0, Y0
	EXP8
	VMOVUPS Y3, (DI)
	VADDPS  Y3, Y14, Y14
	ADDQ    $32, SI
	ADDQ    $32, DI
	DECQ    CX
	JNZ     esloop
esdone:
	VEXTRACTF128 $1, Y14, X0
	VADDPS       X14, X0, X0
	VHADDPS      X0, X0, X0
	VHADDPS      X0, X0, X0
	MOVSS        X0, ret+32(FP)
	VZEROUPPER
	RET

